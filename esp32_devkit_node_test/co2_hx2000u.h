/*
 * CO2 센서 모듈 — EXSEN HX-2000U (전기화학식, UART) (2026-10-13)
 * ------------------------------------------------------------------
 * 센서: EXSEN HX-2000U CO2 Sensor Module (Preliminary Specification Sheet Rev.1, Aug. 2020).
 *   전원 5V(4.5~5.5V), 예열 중 최대 0.15A(0.75W), 예열 뒤 약 0.1W. 측정 범위 400~5,000 ppm, 분해능 1 ppm.
 *   정확도는 "시작 15분 뒤" 기준 ±40ppm ±3%. 처음 1분은 수백 % 오차, 3분 ±100ppm±10%, 10분 ±70ppm±5%.
 *   샘플링 1Hz. 자동 보정(2일 연속 가동 뒤 안정). 온도 보상 소자라 급격한 온도 변화(팬 바람)에 흔들림.
 *   7핀 2.0mm 피치: 1 VCC · 2 GND · 3 Tx(센서 출력) · 4 Rx(센서 입력) · 5 RST · 6·7 NC. 커넥터 미장착.
 *
 * 배선 (v2 2026-10-16 사용자 결정: UART1 TX GPIO19 / RX GPIO18. 시험 폴더는 32/33):
 *   센서 1 VCC ← 보드 5V(VIN) · 센서 2 GND ↔ GND 공통 · 센서 4 Rx ← GPIO19 직결(3.3V 로 충분) ·
 *   센서 3 Tx → 10kΩ → GPIO18, GPIO18–GND 20kΩ (Tx 실측 5V, 2026-10-16 실기 통과. 시트에는 UART 전압이 없었음).
 *   5 RST 는 극성이 시트에 없어 미연결(GND 에 묶지 말 것).
 *
 * ── 통신 (시트 "UART" 절) ──
 *   9600 bps, 8 데이터, 패리티 없음, 정지 1비트. 호스트가 7바이트 요청을 보내면 12바이트가 돌아옵니다.
 *     요청: 42 4D E3 00 00 01 72
 *     응답: 42 4D 00 08 [CO2_H][CO2_L][CalA_H][CalA_L][CalB_H][CalB_L][CK_H][CK_L]
 *   CO2(ppm) = CO2_H×256 + CO2_L. Cal_A·Cal_B 는 보정 번호라 계산에 쓰지 않음(진단 표시만).
 *   체크섬 = 앞 10바이트 합. CK_H = 합/256, CK_L = 합%256. (시작 바이트 "BM"·0xE3 명령은 Plantower 계열 규격)
 *
 * ── 진행 방식 (논블로킹, UART1) ──
 *   CO2_PERIOD_MS 마다 요청을 보내고 CO2_TIMEOUT_MS 안에 응답을 기다립니다. 수신 버퍼에서 머리
 *   [42][4D][00][08] 을 찾아 체크섬을 검사하므로 센서가 스스로 내보내는 프레임이 섞여도 받아집니다.
 *   연속 실패가 CO2_MAX_FAILS 에 닿으면 없음(-1) 처리 뒤 계속 재시도합니다. 주소 탐색은 없습니다(단일 장치).
 *
 * ── 예열 (사용자 결정 2026-10-13: 예열 중에는 co2_ppm 을 null 로 · 2026-10-16: 15분 → 3분) ──
 *   첫 유효 응답(또는 잃었다가 다시 받은 때)부터 CO2_WARMUP_MS(3분) 동안은 예열 중으로 보아 ppm() 이 -1 을
 *   돌려주고 텔레메트리는 null 입니다. 시리얼 상태 줄에는 rawPpm() 으로 값과 "(예열 N분)" 을 함께 보입니다.
 *   3분은 시트의 대표 예열 시간(이때 오차 ±100ppm±10%). 정식 사양(±40ppm±3%)은 15분부터라 처음 15분 값은 참고용.
 *   보드만 소프트 리셋(원격 업로드)되면 센서는 계속 켜져 있어도 3분을 다시 세지만 무해합니다.
 *
 * ── 보고 ──
 *   텔레메트리: co2_ok · co2_ppm(예열 중·없음이면 null). status: co2_ok.
 *   시리얼 co : 통계·값·Cal·마지막 프레임, cor : 즉시 읽기.
 */

#ifndef CO2_HX2000U_H
#define CO2_HX2000U_H

#include <Arduino.h>

namespace co2 {

// UART1 을 열고 첫 요청을 예약합니다. g19/g18 핀 시험 뒤 다시 불러도 됩니다(예열 시계는 유지).
void begin();

// 루프마다 호출. 요청 보내기·응답 모으기·시간 초과 판정을 한 단계씩 진행합니다.
void tick();

bool ok();            // 최근 유효 응답이 있고 아직 잃지 않았는지
bool warmingUp();     // ok 이고 첫 응답 뒤 CO2_WARMUP_MS 가 안 지났는지
int  ppm();           // CO2 ppm. 예열 중·없음이면 -1 (텔레메트리용)
int  rawPpm();        // 예열 중에도 값. 없으면 -1 (시리얼 표시용)
uint32_t warmupRemainingMs();   // 예열 남은 시간. 예열 아니면 0

// 시리얼 cor: 주기를 기다리지 않고 바로 한 번 읽습니다.
void readNow();

void reportSerial();  // 시리얼 s / co: 통계·값·Cal_A/Cal_B·마지막 프레임

}  // namespace co2

#endif  // CO2_HX2000U_H
